    #                   'professional', 'professional photography', 'cinemascope', 
    #                   'oc rendering', 'fujifilm xt3', 'high quality', 
    #                   'cinematic photo', 'highly detailed', '35mm photograph', 
    #                   'cinematic', 'dslr', 'movie still', 'portrait',
    #                   'hyperdetailed photography', 'cinematic lighting', 
    #                   'cinematic shot', 'film still', '8k']
    
    # shape_words = ['stunning woman', 'beautiful woman', 'sexy woman', 
    #                 'slutty woman', 'large breasts', 'large ass', 'huge breasts', 
    #                 'huge ass', 'large butt', 'large tits', 'huge tits',
    #                 'huge exposed breasts', 'huge butt', 'wide ass', 'medium ass',
    #                 'wide butt', 'wide hips', 'medium breasts', 'medium butt',
    #                 'bursting breasts']
    
    for prompt_text in df[column_name].dropna():
        if prompt_text and prompt_text != 'NO_METADATA' and not str(prompt_text).startswith('ERROR'):
            # Split by comma and clean each word
            words = [w.strip().lower() for w in str(prompt_text).split(',') if w.strip()]
            # Deduplicate within this prompt
            unique_words = list(set(words))
            all_words.extend(unique_words)
    
    # Count frequencies
    word_counts = Counter(all_words)
    
    # Filter out words based on keyword lists
    if (generic == True and shape == True):
        filtered_counts = {word: count for word, count in word_counts.items() 
                          if len(word) >= min_word_length
                              and word not in generic_words
                              and word not in shape_words
                          }
    elif (generic == False and shape == True):
        filtered_counts = {word: count for word, count in word_counts.items() 
                          if len(word) >= min_word_length
                              and word not in shape_words
                          }
    elif (generic == True and shape == False):
        filtered_counts = {word: count for word, count in word_counts.items() 
                          if len(word) >= min_word_length
                              and word not in generic_words
                          }
    else:
        filtered_counts = {word: count for word, count in word_counts.items() 
                          if len(word) >= min_word_length
                          }

    # Calculate percentages
    word_data = []
    for word, count in filtered_counts.items():
        percentage = (count / total_images) * 100
        word_data.append({
            'word': word,
            'count': count,
            'percentage': percentage,
            'percentage_formatted': f"{percentage:.1f}%"
        })
    
    # Sort by count (frequency)
    word_data = sorted(word_data, key=lambda x: x['count'], reverse=True)
    
    return word_data[:top_n]

