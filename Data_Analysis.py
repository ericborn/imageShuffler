# Function to create percentage bar chart
def create_percentage_bar_chart(data, title, filename, color):
    """Create a horizontal bar chart showing percentages"""
    words = [item['word'] for item in data]
    percentages = [item['percentage'] for item in data]
    counts = [item['count'] for item in data]
    
    fig, ax = plt.subplots(figsize=(14, 10))
    bars = ax.barh(words, percentages, color=color, edgecolor='black', linewidth=0.5)
    
    ax.set_xlabel('Percentage of Images (%)', fontsize=12, fontweight='bold')
    ax.set_title(title, fontsize=14, fontweight='bold')
    ax.invert_yaxis()  # Most frequent at top
    ax.grid(axis='x', alpha=0.3)
    ax.set_axisbelow(True)
    
    # Add labels with both percentage and count
    for bar, count, pct in zip(bars, counts, percentages):
        width = bar.get_width()
        ax.text(width + 0.5, bar.get_y() + bar.get_height()/2, 
                f'{pct:.1f}% ({count})', 
                ha='left', va='center', fontsize=9, fontweight='bold')
    
    plt.tight_layout()
    plt.savefig(filename, dpi=300, bbox_inches='tight')
    plt.show()

